/**
 * Regenerates packages/shared/src/twemoji.ts: for every emoji character the game and the editor
 * use as an icon, the name of its class in the Twemoji Awesome stylesheet (`twa-<name>`).
 *
 *   node tools/make-twemoji-map.mjs <path to a checkout of github.com/iamludal/twemoji-awesome>
 *
 * The checkout supplies emoji.json (which character has which code points). The class names are
 * read from the stylesheet vendored in packages/shared/assets, so the two cannot disagree. Run it
 * after adding an emoji to the interface; a character with no entry is drawn as plain text.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const checkout = process.argv[2];
if (!checkout) throw new Error('Give the path to a checkout of twemoji-awesome (for its emoji.json).');

const css = readFileSync(join(root, 'packages/shared/assets/twemoji-awesome.css'), 'utf8');
const classOf = new Map();
for (const m of css.matchAll(/\.twa-([a-z0-9-]+) \{ background-image: url\([^)]*\/([0-9a-f-]+)\.svg\)/g)) {
  if (!classOf.has(m[2])) classOf.set(m[2], m[1]);
}
const nameOf = new Map();
for (const e of JSON.parse(readFileSync(join(checkout, 'emoji.json'), 'utf8'))) {
  const codes = e.codes.toLowerCase().split(' ');
  const name = classOf.get(codes.join('-')) ?? classOf.get(codes.filter((c) => c !== 'fe0f').join('-'));
  if (!name) continue;
  nameOf.set(e.char, name);
  // The same emoji typed without its variation selector.
  nameOf.set(e.char.replace(/️/g, ''), name);
}

// Every emoji that appears in the source of the interface.
const files = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.ts$/.test(entry) && !entry.endsWith('twemoji.ts')) files.push(path);
  }
};
for (const dir of ['packages/shared/src', 'apps/client/src', 'apps/editor/src']) walk(join(root, dir));
const known = [...nameOf.keys()].sort((a, b) => b.length - a.length);
const used = new Map();
for (const file of files) {
  const text = readFileSync(file, 'utf8');
  for (const char of known) if (text.includes(char)) used.set(char, nameOf.get(char));
}

const lines = [...used.entries()].sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0])).map(([char, name]) => `  ${JSON.stringify(char)}: '${name}',`);
writeFileSync(join(root, 'packages/shared/src/twemoji.ts'), `// Generated by tools/make-twemoji-map.mjs. Do not edit by hand.

/**
 * The emoji the interface uses, each with the name of its class in the Twemoji Awesome
 * stylesheet (packages/shared/assets/twemoji-awesome.css): \`twa-<name>\`.
 */
export const TWEMOJI: Record<string, string> = {
${lines.join('\n')}
};
`);
console.log(`${used.size} emoji mapped`);
